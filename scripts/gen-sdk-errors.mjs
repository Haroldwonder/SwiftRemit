#!/usr/bin/env node
// Generate the SDK's on-chain error values directly from src/errors.rs.
// Usage: node scripts/gen-sdk-errors.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(resolve(root, "src/errors.rs"), "utf8");
const body = source.match(/\bpub\s+enum\s+ContractError\s*\{([\s\S]*?)^\}/m)?.[1];
if (!body) throw new Error("Cannot find Rust ContractError enum in src/errors.rs");
const entries = Array.from(body.matchAll(/^\s*([A-Za-z][A-Za-z0-9_]*)\s*=\s*(\d+)\s*,\s*$/gm),
  ([, name, value]) => ({ name, value: Number(value) }));
if (entries.length < 60) throw new Error(`Parsed only ${entries.length} ContractError values`);
const names = new Set(entries.map(e => e.name));
const values = new Set(entries.map(e => e.value));
if (names.size !== entries.length || values.size !== entries.length) {
  throw new Error("Duplicate ContractError names or numeric discriminants");
}
const content = [
  "// AUTO-GENERATED by scripts/gen-sdk-errors.mjs from src/errors.rs; do not edit.",
  "/** On-chain contract error codes (single source of truth: src/errors.rs). */",
  "export enum ErrorCode {",
  ...entries.map(e => `  ${e.name} = ${e.value},`),
  "}",
  "",
].join("\n");
const output = resolve(root, "sdk/src/errors.generated.ts");
if (process.argv.includes("--check")) {
  let current;
  try { current = readFileSync(output, "utf8"); } catch { current = ""; }
  if (current !== content) {
    console.error("SDK generated error codes are stale. Run: npm run gen:errors (from sdk/)");
    process.exitCode = 1;
  } else {
    console.log("SDK error codes match src/errors.rs");
  }
} else {
  writeFileSync(output, content, "utf8");
  console.log(`Generated ${entries.length} contract error codes`);
}
